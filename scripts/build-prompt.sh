#!/usr/bin/env bash
# Regenerates adapters/mobbin-design-research.prompt.md and adapters/cursor/mobbin-design-research.mdc
# from skills/mobbin-design-research/. Run after editing the skill.
set -euo pipefail
cd "$(dirname "$0")/.."
S=skills/mobbin-design-research
OUT=adapters/mobbin-design-research.prompt.md
MDC=adapters/cursor/mobbin-design-research.mdc

strip_fm() { awk 'BEGIN{f=0} NR==1&&$0=="---"{f=1;next} f&&$0=="---"{f=0;next} !f{print}' "$1"; }

# Rewrite relative .md links to in-document anchors.
rewrite() {
  sed -E \
    -e 's#\]\((\.\./)?(references/)?project-config\.template\.md\)#](\#part-project-config-template)#g' \
    -e 's#\]\((\.\./)?(references/)?flow-from-scratch\.md\)#](\#part-flow-from-scratch)#g' \
    -e 's#\]\((\.\./)?(references/)?improve-a-screen\.md\)#](\#part-improve-a-screen)#g' \
    -e 's#\]\((\.\./)?(references/)?methods\.md\)#](\#part-methods)#g' \
    -e 's#\]\((\.\./)?(examples/)?REFERENCES\.example\.md\)#](\#part-references-example)#g' \
    -e 's#\]\((\.\./)?(examples/)?PATTERNS\.example\.md\)#](\#part-patterns-example)#g'
}

part() { # id title file
  printf '\n---\n\n<a id="%s"></a>\n\n## %s\n\n' "$1" "$2"
  # drop the file's own H1 and demote the remaining headings by one level
  strip_fm "$3" | awk 'BEGIN{h=0} /^# /&&!h{h=1;next} /^#{2,} /{print "#" $0;next} {print}' | rewrite
}

body() {
  cat <<'HDR'
<!--
HOW TO USE THIS FILE
Generated by scripts/build-prompt.sh from skills/mobbin-design-research/. Do not edit by hand.
Paste the whole file into: a Custom GPT or ChatGPT Project's instructions, a Gemini Gem, a Claude Project,
or any system prompt. Tools with a skills folder (Claude Code, Codex, Cursor, Gemini CLI, Copilot)
should install the skill instead (see README).
Mobbin access: the official Mobbin MCP (https://api.mobbin.com/mcp, OAuth; requires a paid Mobbin plan: Pro, Team
or Enterprise; docs https://mobbin.com/mcp and https://github.com/mobbin/mobbin-mcp-server). If your chat app can connect
it (for example, if your ChatGPT plan supports MCP connectors), do so. Otherwise the "Without the Mobbin MCP" section applies: share Mobbin
links, screenshots or your exported collection in the chat.
-->

HDR
  printf '# Mobbin design research (full prompt)\n\n'
  strip_fm "$S/SKILL.md" | awk 'BEGIN{h=0} /^# /&&!h{h=1;next} /^#{2,} /{print "#" $0;next} {print}' | sed -E 's/^## /## /' | rewrite
  part part-flow-from-scratch "Playbook: flow from scratch" "$S/references/flow-from-scratch.md"
  part part-improve-a-screen "Playbook: improve a screen" "$S/references/improve-a-screen.md"
  part part-methods "Methods: flows and components" "$S/references/methods.md"
  part part-project-config-template "Project config template" "$S/references/project-config.template.md"
  part part-references-example "Example: REFERENCES.md" "$S/examples/REFERENCES.example.md"
  part part-patterns-example "Example: PATTERNS.md" "$S/examples/PATTERNS.example.md"
}

body > "$OUT"

DESC=$(awk '/^description:/{sub(/^description: */,"");print;exit}' "$S/SKILL.md")
{
  printf -- '---\ndescription: %s\nalwaysApply: false\n---\n\n' "$DESC"
  # full content (works in Cursor versions without skills support); drop the HTML comment header
  awk '/^-->/{s=1;next} s' "$OUT"
} > "$MDC"
echo "wrote $OUT ($(wc -l < "$OUT") lines) and $MDC"
